/**
 * Samples an accent colour from each game cover and writes data/art-accents.js.
 *
 * The console shelf used to do this in the browser: on every visit it loaded
 * all sixteen covers purely to read their pixels, one canvas at a time on the
 * main thread, in the seconds right after the page appeared. On a phone that
 * was fifteen long tasks in a row - the page stuttering under the first scroll
 * - for colours that only change when a cover file does.
 *
 * Same weighting as before: a plain average turns to mud, so pixels are
 * weighted by saturation and penalised at the extremes of brightness.
 *
 * Re-run with `npm run accents` after adding or replacing a cover.
 */
import { readdir, writeFile } from "node:fs/promises";
import { join, parse } from "node:path";
import sharp from "sharp";

const COVERS = join(process.cwd(), "assets", "img", "gaming");
const SIZE = 24;

async function sampleAccent(file) {
  const { data } = await sharp(file)
    .resize(SIZE, SIZE, { fit: "fill", kernel: "linear" })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  let r = 0;
  let g = 0;
  let b = 0;
  let total = 0;

  for (let i = 0; i < data.length; i += 3) {
    const pr = data[i] / 255;
    const pg = data[i + 1] / 255;
    const pb = data[i + 2] / 255;

    const max = Math.max(pr, pg, pb);
    const min = Math.min(pr, pg, pb);
    const saturation = max === 0 ? 0 : (max - min) / max;
    const brightness = (max + min) / 2;

    // Favour saturated, mid-bright pixels; ignore near-black and near-white.
    const weight = saturation * saturation * Math.sin(Math.PI * brightness) + 0.02;

    r += pr * weight;
    g += pg * weight;
    b += pb * weight;
    total += weight;
  }

  const channel = (value) => Math.round(Math.min(1, value / total) * 255);
  return `rgb(${channel(r)} ${channel(g)} ${channel(b)})`;
}

const files = (await readdir(COVERS, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && /\.(jpe?g|png|webp)$/i.test(entry.name))
  .map((entry) => entry.name)
  .sort();

const accents = {};
for (const name of files) {
  accents[parse(name).name] = await sampleAccent(join(COVERS, name));
}

const output = `/**
 * GENERATED by scripts/generate-art-accents.mjs - do not edit by hand.
 * Accent colour sampled from each game cover, keyed by game id.
 */
export const artAccents = ${JSON.stringify(accents, null, 2)};
`;

await writeFile(join(process.cwd(), "data", "art-accents.js"), output);
console.log(`[accents] wrote ${files.length} colours to data/art-accents.js`);
